#!/usr/bin/env python3
"""Extract GAME_DATA verbatim from the v1 file into game-data.js.

Reads ~/workspace/timeline-restorer/v1/timeline-restorer.html, finds the
`const GAME_DATA = {...};` object literal by brace matching, and writes it
out as a standalone JS file that defines the same const. The data is NOT
edited — v2 consumes v1's content (acts, scenes, characters, items,
recipes, truths, puzzles, dialogues, quizzes, timelineEvents) unchanged.

Usage: python3 extract_data.py   (run from the v2 folder)
"""
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
V1 = Path.home() / "workspace" / "timeline-restorer" / "v1" / "timeline-restorer.html"
OUT = HERE / "game-data.js"

src = V1.read_text(encoding="utf-8")
m = re.search(r"<script>(.*?)</script>", src, re.S)
if not m:
    sys.exit("no <script> block found in v1 file")
js = m.group(1)
start = js.index("const GAME_DATA = {")
i = js.index("{", start)
depth = 0
j = i
in_str = None
esc = False
while j < len(js):
    c = js[j]
    if in_str:
        if esc:
            esc = False
        elif c == "\\":
            esc = True
        elif c == in_str:
            in_str = None
    else:
        if c in "\"'`":
            in_str = c
        elif c == "{":
            depth += 1
        elif c == "}":
            depth -= 1
            if depth == 0:
                break
    j += 1
data_js = js[i : j + 1]
# The literal is valid JavaScript but not strict JSON, so parse it with
# Node and re-emit canonical JSON (this also validates it).
node_src = (
    "const fs=require('fs');\n"
    "const src=fs.readFileSync(process.argv[2],'utf8');\n"
    "const data=eval('('+src+')');\n"
    "process.stdout.write(JSON.stringify(data));\n"
)
tmp_js = HERE / ".gamedata_raw_tmp.js"
tmp_js.write_text(data_js, encoding="utf-8")
tmp_node = HERE / ".gamedata_parse_tmp.js"
tmp_node.write_text(node_src, encoding="utf-8")
import subprocess
r = subprocess.run(["node", str(tmp_node), str(tmp_js)], capture_output=True, text=True)
tmp_js.unlink(missing_ok=True)
tmp_node.unlink(missing_ok=True)
if r.returncode != 0:
    sys.exit("node failed to parse GAME_DATA: " + r.stderr)
data = json.loads(r.stdout)
assert "</script" not in r.stdout.lower(), "data contains a script-closing tag"
assert "http://" not in r.stdout and "https://" not in r.stdout, "data contains a URL"

OUT.write_text(
    '"use strict";\n'
    "/* GAME_DATA ported verbatim from Timeline Restorer v1.\n"
    "   Generated by extract_data.py — do not hand-edit; re-run the script. */\n"
    "const GAME_DATA = " + json.dumps(data, ensure_ascii=False) + ";\n",
    encoding="utf-8",
)
print("acts:", len(data["acts"]), "| scenes:", len(data["scenes"]),
      "| characters:", len(data["characters"]), "| items:", len(data["items"]),
      "| recipes:", len(data["recipes"]), "| truths:", len(data["truths"]),
      "| puzzles:", len(data["puzzles"]), "| quizzes:", len(data["quizzes"]),
      "| dialogues:", len(data["dialogues"]), "| timelineEvents:", len(data["timelineEvents"]))
print("wrote", OUT, OUT.stat().st_size, "bytes")
